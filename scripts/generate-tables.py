#!/usr/bin/env python3
"""Generate exact Lean vectors from pinned, hash-checked upstream table literals.

This tool never evaluates sin/tan/atan. Default checks the checked-in module;
--write explicitly regenerates it. Fetch sources with scripts/test-fidelity --fetch.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
import fidelity_reference as reference


def generate():
    src = reference.sources()["src/tables.c"]
    out = '''/-
Generated by scripts/generate-tables.py from Chocolate Doom 3.1.1 tables.c,
commit 410d96855b5df5410ff591a90efeafa889119224. Do not regenerate with trig functions.
Copyright (C) 1993-1996 id Software, Inc.; (C) 2005-2014 Simon Howard.
SPDX-License-Identifier: GPL-2.0-or-later. See COPYING.md.
-/
import Init.Data.Vector.Basic

set_option maxRecDepth 4096

namespace Doom.Tables
'''
    for source, dest, ty, size in [("finetangent", "fineTangent", "Int32", 4096),
                                   ("finesine", "fineSine", "Int32", 10240),
                                   ("tantoangle", "tanToAngle", "UInt32", 2049)]:
        match = re.search(r"const \w+ " + source + r"\[\d+\]\s*=\s*\{([^}]+)\}", src)
        if not match:
            raise RuntimeError(f"missing table: {source}")
        values = [int(v.strip()) for v in match[1].split(",") if v.strip()]
        if len(values) != size:
            raise RuntimeError(f"wrong {source} size: {len(values)}")
        chunks = []
        for offset in range(0, size, 256):
            chunk = values[offset:offset+256]
            name = f"{dest}{offset//256}"
            chunks.append(name)
            out += f"\nprivate def {name} : Vector {ty} {len(chunk)} := ⟨#[\n"
            for start in range(0, len(chunk), 8):
                out += "  " + ", ".join(map(str, chunk[start:start+8]))
                out += ",\n" if start+8 < len(chunk) else "\n"
            out += "], by decide⟩\n"
        out += f"\ndef {dest} : Vector {ty} {size} :=\n  " + " ++\n  ".join(chunks) + "\n"
    return out + "\nend Doom.Tables\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    path = ROOT / "Doom/Tables.lean"
    generated = generate()
    if args.write:
        path.write_text(generated)
    elif path.read_text() != generated:
        raise SystemExit("Doom/Tables.lean differs from pinned tables; review/regenerate explicitly")
    print("Exact table generation checked: 4096 tangents, 10240 sines, 2049 arctangents")


if __name__ == "__main__":
    main()
