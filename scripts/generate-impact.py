#!/usr/bin/env python3
"""Extract puff/blood state metadata from the pinned original info.c."""
import importlib.util
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('death_data',ROOT/'scripts/generate-death.py')
data=importlib.util.module_from_spec(spec); spec.loader.exec_module(data)
rows,ids,_,_=data.data()
labels=[r[-1] for r in rows if r[-1].startswith(('S_PUFF','S_BLOOD')) and not r[-1].startswith('S_BLOODY')]
assert len(labels)==7
out='''/- Generated by scripts/generate-impact.py from pinned Chocolate Doom 3.1.1 info.c.
Copyright id Software / Simon Howard. GPL-2.0-or-later. See COPYING.md. -/
import Doom.Death
namespace Doom.ImpactData
'''
for label in labels: out+=f'def {label[2:]} : Nat := {ids[label]}\n'
out+='def frames : Array Death.Frame := #[\n'
out+=',\n'.join(f'  ⟨{ids[label]},"{label}","{rows[ids[label]][0][4:]}",{rows[ids[label]][1]},{rows[ids[label]][2]},{ids[rows[ids[label]][4]]},"{rows[ids[label]][3]}"⟩' for label in labels)
out+='\n]\nend Doom.ImpactData\n'
p=ROOT/'Doom/ImpactData.lean'
if '--write' in sys.argv: p.write_text(out)
elif p.read_text()!=out: raise SystemExit('ImpactData.lean differs from pinned info.c')
