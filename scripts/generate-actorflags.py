#!/usr/bin/env python3
"""Generate sector-change metadata from pinned original mobjinfo fields."""
import argparse
from pathlib import Path
import re
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tests'))
import fidelity_reference as reference

def generate():
    source=reference.sources()['src/doom/info.c']
    out='''/-
Generated by scripts/generate-actorflags.py from pinned Chocolate Doom 3.1.1 info.c.
Commit 410d96855b5df5410ff591a90efeafa889119224.
Copyright (C) 1993-1996 id Software; (C) 2005-2014 Simon Howard.
SPDX-License-Identifier: GPL-2.0-or-later. See COPYING.md.
-/
namespace Doom

structure ActorFlags where
  health : Int32
  shootable : Bool
  noBlockmap : Bool
  noSector : Bool
  deriving Inhabited

def actorFlags : Nat → Option ActorFlags
'''
    count=0
    for entry in re.findall(r'\{\s*// MT_\w+(.*?)\n    \}',source,re.S):
        fields={key:value.strip() for value,key in re.findall(r'^\s*([^\n,]+),?\s*// (\w+)',entry,re.M)}
        editor=int(fields['doomednum'])
        if editor<0: continue
        flags=[flag.strip() for flag in fields['flags'].split('|')]
        values=[fields['spawnhealth']]+[str(flag in flags).lower() for flag in ('MF_SHOOTABLE','MF_NOBLOCKMAP','MF_NOSECTOR')]
        out+=f'  | {editor} => some ⟨'+', '.join(values)+'⟩\n';count+=1
    assert count==118,count
    return out+'  | _ => none\n\nend Doom\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    path=ROOT/'Doom/ActorFlags.lean';text=generate()
    if args.write: path.write_text(text)
    elif path.read_text()!=text: raise SystemExit('ActorFlags.lean differs from pinned metadata')
