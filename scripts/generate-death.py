#!/usr/bin/env python3
"""Generate death chains for the supported player/zombieman/shotgunner/demon/imp/barrel roster."""
import re,sys,argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tests'))
import fidelity_reference as reference

def data():
    src=reference.sources()['src/doom/info.c']
    rows=re.findall(r'\{(SPR_\w+),(-?\d+),(-?\d+),\{(\w+)\},(S_\w+),0,0\},\s*// (S_\w+)',src)
    assert len(rows)>900,len(rows)
    ids={r[-1]:i for i,r in enumerate(rows)}
    assert ids['S_NULL']==0
    metas=[];chosen={'S_GIBS'}
    for kind,entry in re.findall(r'\{\s*// (MT_\w+)(.*?)\n    \}',src,re.S):
        if kind not in ('MT_PLAYER','MT_POSSESSED','MT_SHOTGUY','MT_SERGEANT','MT_TROOP','MT_BARREL'):continue
        f={k:v.strip() for v,k in re.findall(r'^\s*([^\n,]+),?\s*// (\w+)',entry,re.M)}
        for label in (f['deathstate'],f['xdeathstate']):
            while label!='S_NULL' and label not in chosen:
                chosen.add(label);label=rows[ids[label]][4]
        metas.append((kind,f))
    order=['MT_PLAYER','MT_POSSESSED','MT_SHOTGUY','MT_SERGEANT','MT_TROOP','MT_BARREL']
    metas.sort(key=lambda m:order.index(m[0]))
    return rows,ids,metas,chosen

def generate():
    rows,ids,metas,chosen=data()
    flags={'MF_SOLID':2,'MF_SHOOTABLE':4,'MF_DROPOFF':0x400,'MF_PICKUP':0x800,'MF_NOTDMATCH':0x2000000,'MF_COUNTKILL':0x400000,'MF_NOBLOOD':0x80000}
    out='''/-
Generated by scripts/generate-death.py from pinned Chocolate Doom 3.1.1 info.c.
Copyright (C) 1993-1996 id Software; (C) 2005-2014 Simon Howard.
SPDX-License-Identifier: GPL-2.0-or-later. See COPYING.md.
-/
import Doom.Death

namespace Doom.Death

def frames : Array Frame := #[
'''
    values=[]
    for label in sorted(chosen,key=ids.get):
        spr,frame,tics,action,nxt,_=rows[ids[label]]
        values.append(f'  ⟨{ids[label]},"{label}","{spr[4:]}",{frame},{tics},{ids[nxt]},"{action}"⟩')
    out+=',\n'.join(values)+'\n]\n\ndef info : Nat → Option Info\n'
    for kind,f in metas:
        num=0 if kind=='MT_PLAYER' else int(f['doomednum'])
        bits=sum(flags[x.strip()] for x in f['flags'].split('|'))
        out+=f'  | {num} => some ⟨{f["spawnhealth"]},{ids[f["deathstate"]]},{ids[f["xdeathstate"]]},"{f["deathsound"][4:]}",{bits}⟩\n'
    return out+'  | _ => none\n\nend Doom.Death\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    path=ROOT/'Doom/DeathData.lean';text=generate()
    if args.write:path.write_text(text)
    elif path.read_text()!=text:raise SystemExit('DeathData.lean differs from pinned metadata')
