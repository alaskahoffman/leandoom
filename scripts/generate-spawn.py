#!/usr/bin/env python3
"""Generate map-object initial states/countdowns from pinned info.c."""
import argparse
import importlib.util
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('death_data',ROOT/'scripts/generate-death.py')
data=importlib.util.module_from_spec(spec); spec.loader.exec_module(data)

def generate():
    rows,ids,_,_=data.data()
    source=data.reference.sources()['src/doom/info.c']
    out='''/- Generated by scripts/generate-spawn.py from pinned Chocolate Doom 3.1.1 info.c.
Commit 410d96855b5df5410ff591a90efeafa889119224.
Copyright id Software / Simon Howard. GPL-2.0-or-later. See COPYING.md. -/
namespace Doom.MapSpawn

/-- State number and initial duration. Player uses editor number 1 here. -/
def info : Nat → Option (Nat × Int32)
'''
    count=0
    for kind,entry in re.findall(r'\{\s*// (MT_\w+)(.*?)\n    \}',source,re.S):
        fields={k:v.strip() for v,k in re.findall(r'^\s*([^\n,]+),?\s*// (\w+)',entry,re.M)}
        editor=1 if kind=='MT_PLAYER' else int(fields['doomednum'])
        if editor<0: continue
        state=ids[fields['spawnstate']]; tics=int(rows[state][2])
        out+=f'  | {editor} => some ({state}, {tics})\n'; count+=1
    assert count==119,count
    return out+'  | _ => none\n\nend Doom.MapSpawn\n'

if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('--write',action='store_true'); a=p.parse_args()
    path=ROOT/'Doom/SpawnData.lean'; text=generate()
    if a.write: path.write_text(text)
    elif path.read_text()!=text: raise SystemExit('SpawnData.lean differs from pinned metadata')
